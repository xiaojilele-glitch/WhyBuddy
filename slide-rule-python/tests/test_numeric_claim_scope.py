# -*- coding: utf-8 -*-
"""「数字不能编」这道校验，不能把列表标题也当成编的数。

## 事故

2026-08-05 真跑：首页设计生成连挂三次、609 秒零产出，占整轮 30%。三次
失败信息一模一样：

    text 是数据声明（'前5条'）但没有挂 dataRef 聚合

而「前5条」是 rowsRef 的 limit（默认就是 5）在列表标题里的自然说法。它**没有
聚合可挂**——模型改不出能过的写法，重试到耗尽是注定的。

## 为什么会漏

`_NUMERIC_CLAIM_RES` 的注释自称"不拦结构性数字（近7天/Top 5/2026年度）"，
但它靠的是「天/小时/年不在量词表里」这个巧合，没有任何正向白名单。于是同样
形状的标签，命运取决于量词碰巧在不在表里：

    前10名  → 放行（名 不在表里）
    前5条   → 拦下（条 在表里）

这条测试把两边都钉死：取值范围说明词一律放行，真数据声明一个都不许漏。
"""

import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services.freeform_block import _NUMERIC_CLAIM_RES_MATCH as is_claim  # noqa: E402


@pytest.mark.parametrize(
    "text",
    [
        "前5条",            # ← 真机上连挂三次的那一个
        "最近5条",
        "前 5 条报修单",
        "最近3笔",
        "Top 10",
        "Top 5 客户",
        "前10名",
        "第3页",
        # 这四个原本靠"量词不在表里"侥幸放行，现在由结构词规则正面保证
        "近7天趋势",
        "2026年度",
        "24小时",
        "近30天",
    ],
)
def test_列表标题不是数据声明(text):
    """说的是"这个列表打算显示几行"，不是"数据算出来是几"。"""
    assert not is_claim(text), f"「{text}」是取值范围说明，没有聚合可挂，拦下就是死局"


@pytest.mark.parametrize(
    "text",
    [
        "共 42 条",
        "合计 99 人",
        "¥128,000",
        "3.5%",
        "328 单",
        "12,345",
        "128",
    ],
)
def test_真数据声明一个都不许放过(text):
    """放宽结构词不能把本来的防线拆了——这些必须继续要求挂 dataRef。"""
    assert is_claim(text), f"「{text}」是编出来的数，必须拦"


@pytest.mark.parametrize(
    "text,why",
    [
        ("最近30天新增 128 单", "挖掉「最近30」之后，「128 单」仍是实打实的声明"),
        ("前5条中有 42 单超时", "挖掉「前5条」之后，「42 单」仍要拦"),
        ("Top 5 客户贡献 ¥128,000", "挖掉「Top 5」之后，货币金额仍要拦"),
    ],
)
def test_只挖那一小段不挖整句(text, why):
    """结构词豁免的是**它自己那一小段**，不是让整句话免检。

    做成整句豁免的话，一句「最近30天新增 128 单」就能把编造的数字带进页面，
    而且看起来完全合理——这类"放宽放过头"比不放宽危险得多。
    """
    assert is_claim(text), why
